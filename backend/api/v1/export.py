FORBIDDEN_FILE_PATTERNS = [
    r"^\.env.*$",
    r"^.*\.key$",
    r"^.*\.pem$",
    r"^id_rsa.*$",
    r"^.*credential.*$",
    r"^.*secret.*$",
    r"^synq\.db.*$",
    r"^\.git.*$",
]

SECRET_VALUE_PATTERNS = [
    re.compile(r"AIza[0-9A-Za-z-_]{30,}"),               # Google API Key
    re.compile(r"gsk_[a-zA-Z0-9]{30,}"),                # Groq API Key
    re.compile(r"hf_[a-zA-Z0-9]{30,}"),                 # Hugging Face token
    re.compile(r"tvly-[a-zA-Z0-9]{30,}"),               # Tavily API Key
    re.compile(r"AKIA[0-9A-Z]{16}"),                    # AWS Access Key
    re.compile(r"(?:api[_-]?key|secret|password)\s*[:=]\s*['\"][^'\"]+['\"]", re.IGNORECASE),
]


def sanitize_filename(filename: str) -> str:
    """
    Sanitize filename against path traversal attacks (../, absolute paths, null bytes, backslashes).
    """
    if not filename:
        return "untitled_artifact"

    # Block path traversal attempts
    cleaned = filename.replace("\\", "/").strip()
    cleaned = re.sub(r"\.\.+", "", cleaned)  # Remove ..
    cleaned = cleaned.lstrip("/")             # Remove leading slashes
    cleaned = re.sub(r"[\x00-\x1f\x7f]", "", cleaned)  # Remove control characters

    # Remove dangerous characters
    cleaned = re.sub(r'[<>:"|?*]', "_", cleaned)
    parts = [p for p in cleaned.split("/") if p and p != "."]
    safe_path = "/".join(parts) if parts else "unnamed_artifact"

    # Verify no part matches forbidden secret files
    for part in parts:
        lower_part = part.lower()
        for pattern in FORBIDDEN_FILE_PATTERNS:
            if re.match(pattern, lower_part):
                raise ValueError(f"Export of sensitive or forbidden file pattern '{part}' is blocked.")

    return safe_path


def redact_secrets(text: Optional[str]) -> str:
    """Redact known API keys and credentials from exported text deliverables."""
    if not text:
        return ""
    redacted = text
    for pattern in SECRET_VALUE_PATTERNS:
        redacted = pattern.sub("[REDACTED_SECRET]", redacted)
    return redacted


def build_markdown_dossier(
    project: Project,
    tasks: List[Task],
    graph_data: Dict[str, Any],
) -> str:
    """Generate a structured Markdown dossier documenting all project deliverables."""
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: List[str] = [
        f"# Project Dossier: {project.name}",
        "",
        "> **Notice**: This dossier is generated by SYNQ Deterministic AI Orchestration Platform.",
        f"> **Generated at**: {now_str} | **Project ID**: `{project.id}`",
        "",
        "---",
        "",
        "## 1. Project Overview",
        f"- **Domain**: {project.domain.title() if hasattr(project.domain, 'title') else project.domain}",
        f"- **Status**: {project.status.upper() if hasattr(project.status, 'upper') else project.status}",
        f"- **Description**: {project.description or 'No description provided.'}",
        f"- **Total Tasks**: {len(tasks)}",
        "",
        "---",
        "",
        "## 2. Completed Tasks & Deliverables",
        "",
    ]

    completed_tasks = [t for t in tasks if t.status == TaskStatus.COMPLETED.value]
    if not completed_tasks:
        lines.append("_No tasks have reached completed status yet._\n")
    else:
        for idx, t in enumerate(completed_tasks, 1):
            latest_exec = t.executions[-1] if t.executions else None
            provider_str = f"{t.assigned_provider or 'unknown'} ({t.assigned_model or 'default'})"
            lines.extend([
                f"### 2.{idx} {t.title}",
                f"- **Task Type**: `{t.task_type}` | **Priority**: {t.priority}/10",
                f"- **Assigned Provider**: `{provider_str}`",
                f"- **Completed At**: {t.completed_at.strftime('%Y-%m-%d %H:%M:%S UTC') if t.completed_at else 'N/A'}",
            ])

            if t.approval_reason:
                lines.append(f"- **Operator Approval**: Approved by `{t.approved_by or 'Operator'}`: _{t.approval_reason}_")

            if t.acceptance_criteria:
                lines.append(f"- **Acceptance Criteria**: {t.acceptance_criteria}")

            if latest_exec and latest_exec.output_raw:
                content = redact_secrets(latest_exec.output_raw)
                lang = "python" if t.task_type == TaskType.CODE.value else "markdown"
                lines.extend([
                    "",
                    "#### Verified Output:",
                    f"```{lang}",
                    content,
                    "```",
                    "",
                ])

    lines.extend([
        "---",
        "",
        "## 3. Pending, Blocked, or Rejected Tasks",
        "",
    ])

    other_tasks = [t for t in tasks if t.status != TaskStatus.COMPLETED.value]
    if not other_tasks:
        lines.append("_All tasks successfully completed._\n")
    else:
        for t in other_tasks:
            lines.append(f"- **{t.title}** (`{t.status.upper()}`)")
            if t.rejection_reason:
                lines.append(f"  - _Rejection Reason_: {t.rejection_reason}")
            if t.status == TaskStatus.AWAITING_APPROVAL.value:
                lines.append(f"  - _Status_: Requires operator verification before execution.")
            if t.dependencies:
                lines.append(f"  - _Prerequisites_: {t.dependencies}")

    lines.extend([
        "",
        "---",
        "",
        "## 4. Knowledge Graph & Architecture Decisions",
        "",
    ])

    graph_nodes = graph_data.get("nodes", [])
    decision_nodes = [n for n in graph_nodes if n.get("label") == "Decision"]
    if not decision_nodes:
        lines.append("_No explicit architectural decisions recorded in graph memory._\n")
    else:
        for d in decision_nodes:
            desc = d.get("description", "Architectural Decision")
            rat = d.get("rationale", "")
            lines.append(f"- **{desc}**: {rat}")

    lines.extend([
        "",
        "---",
        "",
        "## 5. Security & Verification Audit",
        "- All API keys and secrets were strictly redacted prior to export.",
        "- Output validity was evaluated through deterministic type checkers and second-agent peer review.",
        "",
        "_Generated by SYNQ Platform — Zero-cost, privacy-first deterministic AI orchestration._",
    ])

    return "\n".join(lines)



@router.get("/projects/{project_id}/export/preview")
async def get_export_preview(project_id: str, db: AsyncSession = Depends(get_db)):
    """Preview eligible deliverables and file structure before generating export."""
    res = await db.execute(
        select(Project)
        .options(selectinload(Project.tasks).selectinload(Task.executions))
        .where(Project.id == project_id)
    )
    project = res.scalar_one_or_none()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    completed = [t for t in project.tasks if t.status == TaskStatus.COMPLETED.value]
    deliverable_files = ["manifest.json", "dossier.md", "dependencies.json"]

    for t in completed:
        ext = ".py" if t.task_type == TaskType.CODE.value else ".md"
        safe_name = re.sub(r"[^\w\-_]", "_", t.title[:40]).strip("_")
        deliverable_files.append(f"tasks/{safe_name}{ext}")

    return {
        "project_id": project.id,
        "project_name": project.name,
        "completed_task_count": len(completed),
        "total_task_count": len(project.tasks),
        "deliverable_files": deliverable_files,
        "formats_supported": ["zip", "markdown"],
    }


@router.get("/projects/{project_id}/export/markdown")
async def export_markdown_dossier(project_id: str, db: AsyncSession = Depends(get_db)):
    """Download comprehensive project dossier as Markdown."""
    res = await db.execute(
        select(Project)
        .options(selectinload(Project.tasks).selectinload(Task.executions))
        .where(Project.id == project_id)
    )
    project = res.scalar_one_or_none()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    graph_data = memory_service.get_project_graph(project_id)
    dossier_text = build_markdown_dossier(project, project.tasks, graph_data)

    safe_title = re.sub(r"[^\w\-_]", "_", project.name).strip("_")
    filename = f"{safe_title}_dossier.md"

    return Response(
        content=dossier_text,
        media_type="text/markdown; charset=utf-8",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@router.get("/projects/{project_id}/export/zip")
async def export_zip_archive(project_id: str, db: AsyncSession = Depends(get_db)):
    """
    Generate and stream secure ZIP archive containing all project deliverables:
    - Task deliverables (.py, .md)
    - Full Markdown Dossier
    - Project Manifest (JSON)
    - Dependency graph (JSON)
    Enforces secret-file exclusion and path traversal protection.
    """
    res = await db.execute(
        select(Project)
        .options(selectinload(Project.tasks).selectinload(Task.executions))
        .where(Project.id == project_id)
    )
    project = res.scalar_one_or_none()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    graph_data = memory_service.get_project_graph(project_id)
    dossier_text = build_markdown_dossier(project, project.tasks, graph_data)

    # In-memory ZIP buffer
    zip_buffer = io.BytesIO()

    with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        # 1. Project Manifest
        manifest = {
            "project_id": project.id,
            "project_name": project.name,
            "domain": str(project.domain),
            "exported_at": datetime.now(timezone.utc).isoformat(),
            "task_count": len(project.tasks),
            "completed_tasks": sum(1 for t in project.tasks if t.status == TaskStatus.COMPLETED.value),
            "allowed_providers": project.get_allowed_provider_list(),
            "synq_version": "0.1.0",
        }
        zf.writestr("manifest.json", json.dumps(manifest, indent=2))

        # 2. Markdown Dossier
        zf.writestr("docs/PROJECT_DOSSIER.md", dossier_text)

        # 3. Dependency Graph
        dep_graph = {
            "project_id": project.id,
            "tasks": [
                {
                    "id": t.id,
                    "title": t.title,
                    "status": str(t.status),
                    "dependencies": t.get_dependency_list(),
                }
                for t in project.tasks
            ],
        }
        zf.writestr("dependencies.json", json.dumps(dep_graph, indent=2))

        # 4. Task Deliverables
        for task in project.tasks:
            if task.status == TaskStatus.COMPLETED.value and task.executions:
                latest_exec = task.executions[-1]
                if latest_exec.output_raw:
                    safe_name = re.sub(r"[^\w\-_]", "_", task.title[:50]).strip("_")
                    ext = ".py" if task.task_type == TaskType.CODE.value else ".md"
                    clean_rel_path = sanitize_filename(f"deliverables/{safe_name}{ext}")

                    clean_content = redact_secrets(latest_exec.output_raw)
                    zf.writestr(clean_rel_path, clean_content)

        # 5. Local Artifact Storage (if any exists for this project on disk)
        project_artifact_dir = Path(settings.artifact_local_path) / project.id
        if project_artifact_dir.exists() and project_artifact_dir.is_dir():
            for disk_file in project_artifact_dir.rglob("*"):
                if disk_file.is_file():
                    rel = disk_file.relative_to(project_artifact_dir)
                    try:
                        safe_rel = sanitize_filename(f"artifacts/{rel.as_posix()}")
                        zf.writestr(safe_rel, disk_file.read_bytes())
                    except ValueError:
                        logger.warning("Excluded forbidden file pattern from archive: %s", rel)

    zip_buffer.seek(0)
    safe_title = re.sub(r"[^\w\-_]", "_", project.name).strip("_")
    archive_filename = f"{safe_title}_deliverables.zip"

    return StreamingResponse(
        zip_buffer,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{archive_filename}"'},
    )
